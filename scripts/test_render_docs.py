#!/usr/bin/env python3
"""Tests for render_docs.py. Standard library only; each test drives the CLI as a
subprocess against a throwaway project tree, so it checks behaviour, not internals.

Run: python3 -I scripts/test_render_docs.py
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parent / "render_docs.py"

FM = "---\ntitle: t\nkind: overview\nproject: demo\nupdated: 2026-01-01\n---\n\n"
MERMAID = "```mermaid\nflowchart LR\n  A --> B\n```\n"


def run(project: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-I", str(SCRIPT), *args, str(project)],
        capture_output=True,
        text=True,
        check=False,
    )


def make_project(root: Path, docs: dict[str, str]) -> Path:
    for rel, text in docs.items():
        path = root / "docs" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return root


def generated(project: Path) -> tuple[str, str]:
    gen = project / "docs" / "generated"
    return (
        (gen / "architecture.md").read_text(encoding="utf-8"),
        (gen / "index.html").read_text(encoding="utf-8"),
    )


class RenderTest(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)

    def project(self, docs: dict[str, str], name: str = "p") -> Path:
        return make_project(self.root / name, docs)

    def render(self, docs: dict[str, str]) -> tuple[str, str]:
        project = self.project(docs)
        result = run(project)
        self.assertEqual(result.returncode, 0, result.stderr)
        return generated(project)

    def test_renders_a_diagram_with_title_paragraph_and_source(self) -> None:
        md, html = self.render(
            {"overview.md": FM + "# Overview\n\n## The pipeline\n\nJobs run in a VM.\nSecond line.\n\n" + MERMAID}
        )
        self.assertIn("### The pipeline", md)
        self.assertIn("Jobs run in a VM. Second line.", md)
        self.assertIn("```mermaid\nflowchart LR\n  A --> B\n```", md)
        self.assertIn("Source: [docs/overview.md#the-pipeline](../overview.md#the-pipeline)", md)
        self.assertIn("generated by", md.lower())
        self.assertTrue(md.endswith("\n") and not md.endswith("\n\n"))
        self.assertNotIn("\r", md)
        self.assertIn("<title>demo architecture</title>", html)

    def test_two_renders_are_byte_identical_across_locations(self) -> None:
        docs = {"overview.md": FM + "## A\n\ntext\n\n" + MERMAID, "x.md": "## B\n\n" + MERMAID}
        first = self.render(docs)
        project = self.project(docs, name="elsewhere")
        self.assertEqual(run(project).returncode, 0)
        self.assertEqual(run(project).returncode, 0)
        self.assertEqual(generated(project), first)
        self.assertNotIn(str(self.root), first[0] + first[1])

    def test_files_without_mermaid_and_generated_dir_are_skipped(self) -> None:
        md, _ = self.render(
            {
                "overview.md": FM + "## A\n\n" + MERMAID,
                "plain.md": "## Plain\n\nno diagram\n",
                "generated/old.md": "## Stale\n\n" + MERMAID,
            }
        )
        self.assertNotIn("plain.md", md)
        self.assertNotIn("Stale", md)

    def test_mermaid_inside_a_longer_or_different_fence_is_not_a_diagram(self) -> None:
        doc = (
            "## Real\n\n" + MERMAID + "\n"
            "## Quoted\n\n````markdown\n```mermaid\nflowchart LR\n  FAKE --> X\n```\n````\n\n"
            "~~~text\n```mermaid\nTILDE --> X\n```\n~~~\n\n"
            "## After\n\n" + MERMAID.replace("A --> B", "C --> D")
        )
        md, html = self.render({"overview.md": FM + doc})
        self.assertEqual(md.count("```mermaid"), 2)
        self.assertNotIn("FAKE", md)
        self.assertNotIn("TILDE", html)
        self.assertIn("C --> D", md)
        self.assertIn("### After", md)
        self.assertNotIn("### Quoted", md)

    def test_heading_inside_a_code_fence_is_not_the_title(self) -> None:
        doc = "## Real title\n\n```sh\n# not a heading\n```\n\n" + MERMAID
        md, _ = self.render({"overview.md": FM + doc})
        self.assertIn("### Real title", md)
        self.assertNotIn("### not a heading", md)

    def test_unterminated_mermaid_fence_fails_with_file_and_line(self) -> None:
        project = self.project(
            {
                "overview.md": FM + "## A\n\n" + MERMAID,
                "bad.md": "## Bad\n\ntext\n\n```mermaid\nflowchart LR\n  A --> B\n",
            }
        )
        result = run(project)
        self.assertEqual(result.returncode, 2)
        self.assertIn("docs/bad.md:5", result.stderr)
        self.assertIn("unterminated", result.stderr.lower())

    def test_script_in_heading_and_paragraph_is_escaped_in_html(self) -> None:
        doc = "## <script>alert(1)</script> & co\n\nSee <script>alert(2)</script> now.\n\n" + MERMAID
        _, html = self.render({"overview.md": FM + doc})
        self.assertNotIn("<script>alert", html)
        self.assertIn("&lt;script&gt;alert(1)&lt;/script&gt; &amp; co", html)
        self.assertIn("&lt;script&gt;alert(2)&lt;/script&gt;", html)

    def test_html_is_a_valid_page_with_pinned_mermaid_and_source_fallback(self) -> None:
        diagram = MERMAID.replace("A --> B", 'A --> B["<b>x</b>"]')
        _, html = self.render({"overview.md": FM + "## A\n\n" + diagram})
        self.assertTrue(html.startswith("<!doctype html>"))
        self.assertEqual(len(re.findall(r"<script src=", html)), 1)
        self.assertIn("https://cdn.jsdelivr.net/npm/mermaid@11.4.1/dist/mermaid.min.js", html)
        self.assertIn("securityLevel:'strict'", html.replace(" ", ""))
        self.assertIn("prefers-color-scheme", html)
        self.assertIn('<pre class="mermaid">', html)
        self.assertIn("<details>", html)
        self.assertIn("overflow-x:auto", html.replace(" ", ""))
        self.assertNotIn("<b>x</b>", html)

    def test_order_fixed_files_first_then_alphabetical_then_decisions(self) -> None:
        names = [
            "decisions/zeta.md",
            "decisions/alpha.md",
            "z-last.md",
            "a-first.md",
            "architecture/spec.md",
            "architecture/components.md",
            "architecture/overview.md",
            "overview.md",
        ]
        docs = {n: "## H of " + n + "\n\n" + MERMAID for n in names}
        docs["decisions/nomermaid.md"] = "## none\n"
        md, _ = self.render(docs)
        found = re.findall(r"^Source: \[docs/([^#]+)#", md, flags=re.M)
        self.assertEqual(
            found,
            [
                "overview.md",
                "architecture/overview.md",
                "architecture/components.md",
                "architecture/spec.md",
                "a-first.md",
                "z-last.md",
                "decisions/alpha.md",
                "decisions/zeta.md",
            ],
        )

    def test_anchor_follows_github_rules(self) -> None:
        doc = (
            "## 1. The whole system\n\n" + MERMAID + "\n"
            "## Hello, World! (v2) - `code`\n\n" + MERMAID + "\n"
            "## Same\n\n" + MERMAID + "\n"
            "## Same\n\n" + MERMAID
        )
        md, _ = self.render({"overview.md": FM + doc})
        for anchor in ("1-the-whole-system", "hello-world-v2---code", "same", "same-1"):
            self.assertIn(f"](../overview.md#{anchor})", md)

    def test_table_of_contents_is_grouped_by_file_and_links_resolve(self) -> None:
        md, _ = self.render({"overview.md": FM + "## Same\n\n" + MERMAID, "x.md": "## Same\n\n" + MERMAID})
        toc = md.split("## Contents", 1)[1].split("\n## ", 1)[0]
        self.assertIn("docs/overview.md", toc)
        self.assertIn("docs/x.md", toc)
        self.assertIn("(#same)", toc)
        self.assertIn("(#same-1)", toc)

    def test_long_paragraph_is_trimmed_on_a_sentence_boundary(self) -> None:
        sentence = "This sentence is exactly fifty characters long ok. "
        para = (sentence * 12).strip()
        md, _ = self.render({"overview.md": FM + "## A\n\n" + para + "\n\n" + MERMAID})
        body = md.split("### A\n\n", 1)[1].split("\n\n```mermaid", 1)[0]
        self.assertLessEqual(len(body), 400)
        self.assertTrue(body.endswith("ok."))
        self.assertGreater(len(body), 300)

    def test_check_detects_drift_and_clears_after_regeneration(self) -> None:
        project = self.project({"overview.md": FM + "## A\n\n" + MERMAID})
        self.assertEqual(run(project).returncode, 0)
        self.assertEqual(run(project, "--check").returncode, 0)
        md_path = project / "docs" / "generated" / "architecture.md"
        md_path.write_text(md_path.read_text() + "hand edit\n")
        drift = run(project, "--check")
        self.assertEqual(drift.returncode, 1)
        self.assertIn("architecture.md", drift.stdout + drift.stderr)
        self.assertNotIn("index.html", drift.stdout + drift.stderr)
        self.assertEqual(run(project).returncode, 0)
        self.assertEqual(run(project, "--check").returncode, 0)

    def test_check_fails_when_generated_files_are_missing(self) -> None:
        project = self.project({"overview.md": FM + "## A\n\n" + MERMAID})
        result = run(project, "--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("render_docs.py", result.stdout + result.stderr)


if __name__ == "__main__":
    unittest.main()
